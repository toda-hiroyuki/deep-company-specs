function OperatorLayoutInner({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();

  if (pathname === "/operator/login" || pathname.startsWith("/operator/login/")) {
    return <>{children}</>;
  }

  return (
    <div className="admin-layout">
      <nav className="sidebar" style={{ display: "flex", flexDirection: "column" }}>
        <div className="sidebar-title">Deep Experience</div>
        <ul className="sidebar-nav">
          {NAV_ITEMS.map((item) => (
            <li key={item.href}>
              <Link
                href={item.href}
                className={pathname.startsWith(item.href) ? "active" : ""}
                style={{ display: "flex", alignItems: "center", gap: 10 }}
              >
                {item.icon}
                {item.label}
              </Link>
            </li>
          ))}
        </ul>
        <div className="sidebar-bottom">
          <button
            className="btn btn-ghost btn-sm"
            style={{ width: "100%", color: "#9ca3af" }}
            onClick={() => {
              localStorage.removeItem("operator_token");
              window.location.href = "/operator/login";
            }}
          >
            ログアウト
          </button>
        </div>
      </nav>
      <main className="main-content">{children}</main>
    </div>
  );
}

export default function OperatorLayout({ children }: { children: React.ReactNode }) {
  return <OperatorLayoutInner>{children}</OperatorLayoutInner>;
}
